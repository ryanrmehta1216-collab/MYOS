/* ==========================================================
 * Character Drawing - Background Fill + Foreground Text
 *
 * draw_char_bg:  Renders one 8x16 character cell with both
 *                a solid background fill and foreground text.
 *                This eliminates background bleed-through.
 *
 * draw_string_bg: Renders a complete string with proper
 *                9-pixel horizontal advance per character
 *                (8px char + 1px gap) to prevent overlapping.
 * ========================================================== */

void draw_char_bg(uint32_t x, uint32_t y, char c, uint32_t fg_color, uint32_t bg_color) {
    unsigned char uc = (unsigned char)c;
    if (uc < 32 || uc > 126) return;
    if (x >= SCREEN_WIDTH || y >= SCREEN_HEIGHT) return;

    /* Fill the entire 8x16 character cell with background color */
    for (uint32_t row = 0; row < FONT_H; row++) {
        uint32_t py = y + row;
        if (py >= SCREEN_HEIGHT) break;
        uint32_t offset = py * SCREEN_WIDTH + x;

        uint8_t bits = font8x16[uc - 32][row];
        for (uint32_t col = 0; col < FONT_W; col++) {
            int32_t px = x + col;
            if (px >= SCREEN_WIDTH) break;

            if (bits & (0x80 >> col)) {
                /* Foreground pixel (on) */
                backbuffer[offset + col] = fg_color;
            } else {
                /* Background pixel (off) — explicitly drawn to prevent bleed */
                backbuffer[offset + col] = bg_color;
            }
        }
    }
}

/* draw_char uses the globally set current_bg_color as its background fill.
 * Call set_draw_bg() before drawing to control the fill color.
 * This prevents old text pixels from bleeding through. */
void draw_char(uint32_t x, uint32_t y, char c, uint32_t color) {
    draw_char_bg(x, y, c, color, current_bg_color);
}

void draw_string_bg(uint32_t x, uint32_t y, const char* str, uint32_t fg_color, uint32_t bg_color) {
    if (!str) return;
    uint32_t cur_x = x;
    for (int i = 0; str[i] != '\0'; i++) {
        /* Skip newlines and carriage returns */
        if (str[i] == '\n' || str[i] == '\r') continue;
        draw_char_bg(cur_x, y, str[i], fg_color, bg_color);
        /* Advance by exactly FONT_W + 1 to prevent character overlap */
        cur_x += FONT_W + 1;
    }
}

/* draw_string uses the globally set current_bg_color as its background fill.
 * Call set_draw_bg() before drawing to control the fill color.
 * Each character advances by FONT_W + 1 pixels to prevent overlapping. */
void draw_string(uint32_t x, uint32_t y, const char* str, uint32_t color) {
    draw_string_bg(x, y, str, color, current_bg_color);
}
